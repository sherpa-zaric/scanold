const dict: Record<Loc, Record<string, string>> = { en, zh }

const Ctx = createContext<{ loc: Loc; t: (k: string) => string }>({ loc: 'en', t: (k) => en[k] ?? k })

export function I18nProvider({ loc, children }: { loc: Loc; children: ReactNode }) {
  useEffect(() => {
    document.documentElement.lang = loc === 'zh' ? 'zh-CN' : 'en'
  }, [loc])
  return <Ctx.Provider value={{ loc, t: (k) => dict[loc][k] ?? en[k] ?? k }}>{children}</Ctx.Provider>
}

export const useI18n = () => useContext(Ctx)

export const pathOf = (loc: Loc, path: string) => {
  const p = path === '/' ? '' : path
  if (!p) return loc === 'zh' ? '/zh' : '/'
  return (loc === 'zh' ? '/zh' : '') + p
}
